"""Seed content: the real syllabus structure, plus a starter question bank.

WHY THIS IS A DATA MODULE AND NOT A SCRIPT THAT INSERTS ROWS

Every value here is asserted by a test that runs without a database (see
``tests/test_seed_data.py``): unique codes, weights that sum plausibly, every
option set containing exactly one correct answer, every objective question
carrying an answer. A seed script that only runs against a live database cannot
be checked in CI, so its typos reach production as corrupt reference data - and
reference data is the one thing that is painful to correct after students have
progress attached to it.

THE SYLLABUS IS THE NEW SCHEME (2024). Paper names and groupings follow the
revised structure: Foundation 4 papers; Intermediate 6 papers across Groups I and
II; Final 6 papers. Weights are an editorial estimate of paper weightage, not an
ICAI-published figure - the chapter weighting the planner uses is a planning
input, and the planner is honest about being a plan.
"""

from __future__ import annotations

from typing import NamedTuple

SyllabusScheme = "NEW_2024"


class ChapterSeed(NamedTuple):
    code: str
    name: str
    weightage: int
    estimated_minutes: int


class SubjectSeed(NamedTuple):
    code: str
    name: str
    group: str | None
    paper_number: int
    weight: int
    chapters: tuple[ChapterSeed, ...]


class CourseSeed(NamedTuple):
    code: str
    name: str
    level: str
    description: str
    subjects: tuple[SubjectSeed, ...]


class OptionSeed(NamedTuple):
    label: str
    text: str
    is_correct: bool = False


class QuestionSeed(NamedTuple):
    """A question, keyed by subject and chapter CODE rather than by uuid.

    Ids are generated by the database, so a seed that hard-coded uuids would break
    the moment two environments were seeded independently - and the mock papers
    reference questions by id.
    """

    subject_code: str
    chapter_code: str
    text: str
    options: tuple[OptionSeed, ...]
    explanation: str
    difficulty: str = "MEDIUM"
    question_type: str = "MCQ"
    marks: int = 2


class MockSeed(NamedTuple):
    title: str
    course_code: str
    subject_code: str | None
    kind: str
    duration_min: int
    total_marks: int
    is_premium: bool
    chapter_codes: tuple[str, ...]


