#: Published exam attempts.
#:
#: A SESSION HERE MEANS A MONTH, NOT A LEVEL. `exam_sessions` is unique on
#: (year, month), so it cannot hold "Final - May 2026" and "Intermediate - May
#: 2026" as two rows. That is a real limitation rather than a stylistic choice:
#: Final now runs only in May and November while Intermediate also runs in
#: January, so a per-level calendar needs a `level` column and a wider unique key.
#: Recorded in the build audit; until then the label names the month, and the
#: planner takes the student's own exam date anyway.
#:
#: `exam_start_date` is NULL on purpose: ICAI publishes the calendar separately,
#: and a countdown computed from an invented date is worse than no countdown.
EXAM_SESSIONS: tuple[tuple[int, str, str], ...] = (
    (2026, "MAY", "May 2026"),
    (2026, "NOVEMBER", "November 2026"),
    (2027, "MAY", "May 2027"),
)


def chapter_by_code() -> dict[str, ChapterSeed]:
    return {
        chapter.code: chapter
        for course in COURSES
        for subject in course.subjects
        for chapter in subject.chapters
    }


def subject_by_code() -> dict[str, SubjectSeed]:
    return {subject.code: subject for course in COURSES for subject in course.subjects}


def course_of_subject(subject_code: str) -> CourseSeed:
    for course in COURSES:
        for subject in course.subjects:
            if subject.code == subject_code:
                return course
    raise KeyError(subject_code)
